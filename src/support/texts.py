def ticket_created(ticket_id: int, sla_minutes: int) -> str:
    """Подтверждение создания: id и обещанный срок ответа."""
    return f"✅ Тикет #{ticket_id} создан. Менеджер ответит в течение {sla_minutes} минут."


def confirm_prompt(category: str, subject: str) -> str:
    """Шаг подтверждения: что именно будет создано, до записи в базу."""
    return f"Создать тикет?\nКатегория: {category}\nОписание: {subject}"


def reply_sent(ticket_id: int) -> str:
    """Ответ менеджера ушёл клиенту."""
    return f"✅ Ответ отправлен по тикету #{ticket_id}."


def canned_preview(body: str) -> str:
    """Показ выбранного шаблона перед отправкой."""
    return f"Ответ (шаблон):\n{body}\n\nОтправить? ✅ / ✏️ напишите свой."


def client_replied(ticket_id: int, text: str) -> str:
    """Уведомление менеджеру о новом сообщении клиента."""
    return f"💬 Клиент ответил по тикету #{ticket_id}: {text}"


