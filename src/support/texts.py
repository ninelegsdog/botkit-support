"""Тексты, видимые пользователю, — в одном месте, чтобы не расходиться с кейсами.

Зачем этот модуль
=================

Текст ответа жил строковым литералом прямо в вызове `message.answer(...)`.
Тот же текст был продублирован ещё в двух местах:

* `tests/e2e/test_dialog.py` — константой `START_GREETING`;
* `cases/*.yaml` фермы — в `text_contains`.

Три копии одной строки расходятся при первой же правке: меняешь текст в
обработчике — краснеет e2e-тест, а потом и прогон кейса, и оба раза приходится
вспоминать, где ещё лежит та же фраза. Тест при этом проверяет не поведение, а
удачное совпадение литералов.

Здесь строка объявлена один раз. Обработчики и тесты импортируют константу;
кейсы фермы цитируют **подстроку** из неё (движок сверяет вхождение, не
равенство), поэтому эмодзи-префикс правке не мешает.

Граница модуля
==============

Сюда попадают только строки, которые бот **отправляет как сообщение целиком**
или как отдельную кнопку. Строки-шаблоны с подстановкой (карточка тикета в
`core/ui.py`) остаются в своём модуле: их собирает одна функция, дублировать
нечего, а вынести частичную склейку — значит разрезать логику пополам.

Имена — по роли строки (`WELCOME`, `CHOOSE_CATEGORY`), не по экрану: экран может
переехать, роль остаётся.
"""

